export const LANGUAGES = Object.keys(STRINGS);

function detect() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved && STRINGS[saved]) return saved;
  } catch {}
  const nav = (navigator.language || "en").toLowerCase();
  return LANGUAGES.find((l) => l.toLowerCase() === nav)
    || LANGUAGES.find((l) => l.split("-")[0] === nav.split("-")[0])
    || "en";
}

export let lang = detect();

export function setLang(l) {
  lang = STRINGS[l] ? l : "en";
  try { localStorage.setItem("lang", lang); } catch {}
  document.documentElement.lang = lang;
  applyStatic();
}

export function has(key) {
  return key in STRINGS[lang] || key in STRINGS.en;
}

export function t(key, params = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? params[k] : m));
}

// Translate a server error: {error, code, params} from the API, or a bare code / text.
export function tError(err) {
  if (err && typeof err === "object") {
    return err.code && has(`errors.${err.code}`) ? t(`errors.${err.code}`, err.params || {}) : err.error || String(err);
  }
  return has(`errors.${err}`) ? t(`errors.${err}`) : err;
}

// Elements carry data-i18n="key" (text), data-i18n-placeholder / data-i18n-title (attributes).
export function applyStatic(root = document) {
  for (const e of root.querySelectorAll("[data-i18n]")) e.textContent = t(e.dataset.i18n);
  for (const e of root.querySelectorAll("[data-i18n-placeholder]")) e.placeholder = t(e.dataset.i18nPlaceholder);
  for (const e of root.querySelectorAll("[data-i18n-title]")) e.title = t(e.dataset.i18nTitle);
}
